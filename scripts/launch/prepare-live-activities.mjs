// Adds the DeepHausWidgets app extension that renders expo-widgets Live Activities
// (Dynamic Island and Lock Screen) to the checked-in native project. The project is not
// generated with `expo prebuild`, so this does what the expo-widgets config plugin would
// do, plus the staging and StoreKit configurations the plugin knows nothing about.
// Safe to rerun; it skips the steps that are already applied. Run `pod install` afterwards.
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../../', import.meta.url));
const ios = path.join(root, 'apps/mobile/ios');
const requireMobile = createRequire(path.join(root, 'apps/mobile/package.json'));
const requireExpo = createRequire(requireMobile.resolve('expo/package.json'));
const requirePlugins = createRequire(requireExpo.resolve('@expo/config-plugins/package.json'));
const xcode = requirePlugins('xcode');
const plist = requirePlugins('@expo/plist');
const helper = (name) => requireMobile(`expo-widgets/plugin/build/ios/xcode/${name}.js`);

const targetName = 'DeepHausWidgets';
const groupIdentifier = 'group.com.deephaus.app';
const teamId = 'NVNN9G49JA';
const deploymentTarget = '16.4';
const hostBundleIds = { Debug: 'com.deephaus.app', Release: 'com.deephaus.app', 'Release Staging': 'com.deephaus.app.staging', 'Debug StoreKit': 'com.deephaus.app.staging' };
const quote = (value) => JSON.stringify(String(value));
const changed = [];

// 1. Extension sources. The bundle holds only the Live Activity host; layouts are written in
//    TypeScript (apps/mobile/lib/live-activities) and evaluated by expo-widgets at runtime.
const targetDir = path.join(ios, targetName);
mkdirSync(targetDir, { recursive: true });
const appInfo = plist.default.parse(readFileSync(path.join(ios, 'DeepHaus/Info.plist'), 'utf8'));
const files = {
  'index.swift': `import WidgetKit
import SwiftUI
internal import ExpoWidgets

// Generated by scripts/launch/prepare-live-activities.mjs. Home Screen widgets would be listed
// here as well; DeepHaus only ships Live Activities, which expo-widgets registers at runtime.
@main
struct ExportWidgets0: WidgetBundle {
  var body: some Widget {
    WidgetLiveActivity()
  }
}
`,
  'Info.plist': plist.default.build({
    NSExtension: { NSExtensionPointIdentifier: 'com.apple.widgetkit-extension' },
    ExpoWidgetsAppGroupIdentifier: groupIdentifier,
    // Must match the host app or App Store validation rejects the archive.
    CFBundleShortVersionString: appInfo.CFBundleShortVersionString ?? '1.0',
    CFBundleVersion: appInfo.CFBundleVersion ?? '1',
  }),
  [`${targetName}.entitlements`]: plist.default.build({ 'com.apple.security.application-groups': [groupIdentifier] }),
};
for (const [name, content] of Object.entries(files)) {
  const file = path.join(targetDir, name);
  let current = null;
  try { current = readFileSync(file, 'utf8'); } catch {}
  if (current !== content) { writeFileSync(file, content); changed.push(`${targetName}/${name}`); }
}

// 2. Xcode target, reusing the expo-widgets plugin's project helpers.
const pbxprojPath = path.join(ios, 'DeepHaus.xcodeproj/project.pbxproj');
const project = xcode.project(pbxprojPath);
project.parseSync();
if (project.pbxTargetByName(targetName)) {
  console.log(`${targetName} target already exists; leaving project.pbxproj alone.`);
} else {
  const groupName = 'Embed Foundation Extensions';
  const list = helper('addXCConfigurationList').addXCConfigurationList(project, {
    targetName,
    bundleIdentifier: `${hostBundleIds.Release}.${targetName}`,
    deploymentTarget,
    appleTeamId: teamId,
    marketingVersion: appInfo.CFBundleShortVersionString?.startsWith('$') ? '1.0' : appInfo.CFBundleShortVersionString ?? '1.0',
    currentProjectVersion: appInfo.CFBundleVersion?.startsWith('$') ? '1' : appInfo.CFBundleVersion ?? '1',
  });
  const productFile = helper('addProductFile').addProductFile(project, { targetName, groupName });
  const target = helper('addToPbxNativeTargetSection').addToPbxNativeTargetSection(project, {
    targetName,
    targetUuid: project.generateUuid(),
    productFile,
    xCConfigurationList: list,
  });
  helper('addToPbxProjectSection').addToPbxProjectSection(project, target);
  helper('addTargetDependency').addTargetDependency(project, target);
  helper('addBuildPhases').addBuildPhases(project, { targetUuid: target.uuid, groupName, productFile, widgetFiles: ['index.swift'] });
  helper('addPbxGroup').addPbxGroup(project, { targetName, widgetFiles: ['index.swift', 'Info.plist'] });

  const objects = project.hash.project.objects;
  const projectObject = objects.PBXProject[project.getFirstProject().uuid];
  projectObject.attributes.TargetAttributes[target.uuid] = { DevelopmentTeam: teamId, LastSwiftMigration: 1250, ProvisioningStyle: 'Automatic' };

  // The plugin only knows Debug and Release. Mirror the app target's staging and StoreKit
  // configurations so the extension keeps a bundle identifier prefixed by its host app.
  const configurations = objects.XCConfigurationList[list.uuid].buildConfigurations;
  const byName = Object.fromEntries(configurations.map((item) => [item.comment, item]));
  for (const item of configurations) {
    const config = objects.XCBuildConfiguration[item.value];
    Object.assign(config.buildSettings, {
      CODE_SIGN_STYLE: 'Automatic',
      CODE_SIGN_IDENTITY: quote('Apple Development'),
      SWIFT_OPTIMIZATION_LEVEL: item.comment === 'Release' ? quote('-O') : quote('-Onone'),
    });
  }
  const clones = {
    'Release Staging': { from: 'Release', settings: { SDKROOT: 'iphoneos', SUPPORTED_PLATFORMS: quote('iphoneos iphonesimulator') } },
    'Debug StoreKit': { from: 'Debug', settings: { SDKROOT: 'iphonesimulator', SUPPORTED_PLATFORMS: quote('iphonesimulator'), CODE_SIGN_IDENTITY: quote('-'), CODE_SIGNING_ALLOWED: 'YES' } },
  };
  for (const [name, clone] of Object.entries(clones)) {
    const config = structuredClone(objects.XCBuildConfiguration[byName[clone.from].value]);
    config.name = quote(name);
    Object.assign(config.buildSettings, clone.settings, {
      PRODUCT_BUNDLE_IDENTIFIER: quote(`${hostBundleIds[name]}.${targetName}`),
    });
    const uuid = project.generateUuid();
    objects.XCBuildConfiguration[uuid] = config;
    objects.XCBuildConfiguration[`${uuid}_comment`] = name;
    configurations.push({ value: uuid, comment: name });
  }
  writeFileSync(pbxprojPath, project.writeSync());
  changed.push('DeepHaus.xcodeproj/project.pbxproj');
}

// 3. CocoaPods: a second target that links only expo, expo-widgets and @expo/ui.
const podfilePath = path.join(ios, 'Podfile');
let podfile = readFileSync(podfilePath, 'utf8');
if (!podfile.includes(`target '${targetName}' do`)) {
  podfile = podfile.replace(
    'post_install do |installer|\n',
    'post_install do |installer|\n    # Lets the Live Activity extension link ExpoModulesCore, ExpoUI and React.\n    expo_widgets_post_install(installer)\n\n',
  );
  podfile += `
# Live Activity extension (see scripts/launch/prepare-live-activities.mjs).
require File.join(File.dirname(\`node --print "require.resolve('expo-widgets/package.json')"\`), "scripts/autolinking")
target '${targetName}' do
  use_expo_modules_widgets!

  config_command = [
    'node',
    '--no-warnings',
    '--eval',
    "require(require.resolve('expo-modules-autolinking', { paths: [require.resolve('expo/package.json')] }))(process.argv.slice(1))",
    'react-native-config',
    '--json',
    '--platform',
    'ios'
  ]
  config = use_expo_native_module!(config_command)

  use_frameworks! :linkage => podfile_properties['ios.useFrameworks'].to_sym if podfile_properties['ios.useFrameworks']
  use_frameworks! :linkage => ENV['USE_FRAMEWORKS'].to_sym if ENV['USE_FRAMEWORKS']

  use_react_native!(
    :path => config[:reactNativePath],
    :hermes_enabled => podfile_properties['expo.jsEngine'] == nil || podfile_properties['expo.jsEngine'] == 'hermes',
    :app_path => "#{Pod::Config.instance.installation_root}/..",
    :privacy_file_aggregation_enabled => podfile_properties['apple.privacyManifestAggregationEnabled'] != 'false',
  )
end
`;
  if (!podfile.includes('expo_widgets_post_install(installer)')) throw new Error('Could not find the post_install hook in the Podfile.');
  writeFileSync(podfilePath, podfile);
  changed.push('Podfile');
}

// 4. Host app: Live Activity support flags and the shared App Group.
const hostKeys = {
  NSSupportsLiveActivities: true,
  NSSupportsLiveActivitiesFrequentUpdates: false,
  ExpoWidgetsAppGroupIdentifier: groupIdentifier,
};
for (const file of ['DeepHaus/Info.plist', 'DeepHausStaging-Info.plist', 'DeepHausTestFlight-Info.plist']) {
  const full = path.join(ios, file);
  const current = plist.default.parse(readFileSync(full, 'utf8'));
  const missing = Object.entries(hostKeys).filter(([key]) => !(key in current));
  if (!missing.length) continue;
  if (file.includes('TestFlight')) {
    // prepare-testflight.mjs writes this file with @expo/plist; keep its formatting.
    writeFileSync(full, plist.default.build({ ...current, ...hostKeys }));
  } else {
    for (const [key, value] of missing) {
      execFileSync('plutil', ['-insert', key, typeof value === 'boolean' ? '-bool' : '-string', String(value), full]);
    }
  }
  changed.push(file);
}
const entitlementsPath = path.join(ios, 'DeepHaus/DeepHaus.entitlements');
const entitlements = plist.default.parse(readFileSync(entitlementsPath, 'utf8')) ?? {};
const groups = entitlements['com.apple.security.application-groups'] ?? [];
if (!groups.includes(groupIdentifier)) {
  entitlements['com.apple.security.application-groups'] = [groupIdentifier, ...groups];
  writeFileSync(entitlementsPath, plist.default.build(entitlements));
  changed.push('DeepHaus/DeepHaus.entitlements');
}

console.log(changed.length ? `Updated: ${changed.join(', ')}` : 'Nothing to do.');
console.log('Next: cd apps/mobile/ios && pod install. Device builds also need the App Group enabled for both bundle identifiers and the extension identifiers registered with Apple.');
